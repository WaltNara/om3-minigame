"""Reproduce r4 input-latch gaps; no firmware changes or physical-controller claims.

Reuses the reviewed upstream queue/reply instrumentation generated by
test_flappy_touch_reply.py, but stores independent investigation evidence.
"""
import hashlib
import json
import os
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

R = Path(__file__).resolve().parents[1]
G = R / 'work/flappy-touch-repaired'
O = G / 'touch-misses'
O.mkdir(exist_ok=True)
m = json.loads((G / 'build.json').read_text())
assert hashlib.sha256((G / 'row-main.bin').read_bytes()).hexdigest() == m['candidate_sha256']
assert m['candidate_sha256'] == 'b479f1449ca524656694d1dab4dab461ab3f0f4858a23cda7e6a0cbec64748b0'
src = (G / 'touch-reply/replay.mjs').read_text()
assert 'function appTouch(kind,x=450,y=300)' in src
src = src.replace("  else if(t.startsWith('app-touch:'))", """  else if(t.startsWith('app-burst:')){for(const kind of t.slice(10).split(',').map(Number))appTouch(kind);}
  else if(t.startsWith('app-touch:'))""")
(O / 'replay.mjs').write_text(src)
entry = 's1 ok ok ' + 'down ' * 13 + 'ok ' + 'down ' * 4 + 'ok '
cases = {
    'release-control': ([1, 3, 1, 3], 2, 0),
    'tap-terminal': ([1, 4, 1, 4], 1, 1),
    'double-tap-terminal': ([1, 5, 1, 5], 1, 1),
    'tap-only': ([4, 4], 0, 0),
    'short-contact-release': ('app-burst:1,3', 1, 0),
    'two-before-tick': ('app-burst:1,3,1,3', 1, 0),
}
env = dict(os.environ, OM_EMU_MODEL='E147')
for k in ('NCALL', 'NOUT', 'WATCH', 'GAME_STATE', 'GAME_GC', 'WRANGE', 'WSTACK'):
    env.pop(k, None)


def run_case(name, spec):
    sequence, flaps, contact = spec
    tokens = sequence if isinstance(sequence, str) else ' '.join(f'app-touch:{k},450,300' for k in sequence)
    script = entry + tokens
    with (O / (name + '.log')).open('w') as f:
        subprocess.run(['node', str(O / 'replay.mjs'), (R / 'work/om-emu/emu').as_uri(),
                        str(G / 'row-main.bin'), str(R / 'work/native-build/paired.omsd'),
                        str(O / (name + '.json')), str(O / (name + '.omsd')), script],
                       cwd=R, env=env, stdout=f, stderr=subprocess.STDOUT, check=True, timeout=180)
    j = json.loads((O / (name + '.json')).read_text())
    assert not j['engineErrors']
    e = j['log'][-1]
    t = e['touch']
    assert e['game'] == 6 and e['contact'] == contact and e['pending'] == 0, (name, e)
    assert t['flaps'] == flaps, (name, t)
    assert t['sent'] == t['replies'] == t['waits'] == t['returned'] == t['abi'], (name, t)
    return dict(sequence=sequence, flaps=flaps, contact=contact, protocol=t)


with ThreadPoolExecutor(max_workers=3) as pool:
    jobs = {name: pool.submit(run_case, name, spec) for name, spec in cases.items()}
    results = {name: job.result() for name, job in jobs.items()}
report = dict(status='REPRODUCED input-latch gaps; camera event sequence unmeasured',
              candidate_sha256=m['candidate_sha256'], physical_controller_emulated=False,
              cases=results)
(O / 'summary.json').write_text(json.dumps(report, indent=2))
for name, result in results.items():
    print(name, result, flush=True)
